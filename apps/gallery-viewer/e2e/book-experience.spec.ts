import { test, expect } from '@playwright/test'
import { mockGallery } from './helpers/mockGallery'
import { createRecommendedViewerConfig } from '@vie/gallery-contracts'

test('large book turns, opens a page, fits mobile and restores other spatial arrangements', async ({ page }, info) => {
  const config = createRecommendedViewerConfig()
  config.camera.autoRotate = false
  config.particles.enabled = false
  config.effects.photoFloat = false
  const { errors } = await mockGallery(page, { count: 13, config })
  await page.goto('/g/effects-fixture')
  await page.getByRole('button', { name: '翻页', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__VIE_VIEWER_DIAGNOSTICS__!.snapshot().renderedPhotos.ready)).toBeGreaterThan(0)
  await page.waitForTimeout(1000)
  await page.screenshot({ path: info.outputPath('book-desktop.png') })
  await page.getByRole('button', { name: '下一张作品', exact: true }).click()
  await page.waitForTimeout(200)
  await page.screenshot({ path: info.outputPath('book-turn.png') })
  await expect(page.locator('.stage-counter span').first()).toHaveText('02')
  await page.waitForTimeout(1300)
  await page.mouse.click(850, 340)
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: '下一张作品', exact: true }).click()
  await expect(page.locator('.stage-counter span').first()).toHaveText('03')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('book-mobile.png') })
  await page.getByRole('button', { name: '穿行', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__VIE_VIEWER_DIAGNOSTICS__!.snapshot().renderedPhotos.ready)).toBeGreaterThan(0)
  await page.screenshot({ path: info.outputPath('tunnel-mobile.png') })
  await page.getByRole('button', { name: '螺旋', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__VIE_VIEWER_DIAGNOSTICS__!.snapshot().renderedPhotos.ready)).toBeGreaterThan(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByRole('button', { name: '播放照片编排', exact: true }).click()
  await expect(page.getByRole('region', { name: '照片编排' })).toHaveAttribute('data-status', 'playing')
  await page.getByLabel('照片排列与组合').selectOption('book')
  await page.getByRole('button', { name: '向后翻页' }).click()
  await page.waitForTimeout(1400)
  await page.getByRole('button', { name: '退出编排' }).click()
  await expect(page.getByRole('button', { name: '螺旋', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(errors).toEqual([])
})

test('visitor book navigation wraps small albums and returns from focus', async ({ page }, info) => {
  const { errors } = await mockGallery(page, { count: 2, config: { quality: 'mid', effects: { photoEntrance: 'none' }, particles: { enabled: false } } })
  await page.goto('/g/effects-fixture')
  await page.getByLabel('照片排列与组合').selectOption('book')
  await page.getByRole('button', { name: '向后翻页' }).click()
  await page.waitForTimeout(1700)
  await page.screenshot({ path: info.outputPath('theatre-book.png') })
  await page.getByRole('button', { name: '查看当前主图' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('region', { name: '照片编排' })).toHaveAttribute('data-mode', 'book')
  await page.getByRole('button', { name: '退出编排' }).click()
  await expect.poll(() => page.evaluate(() => window.__VIE_VIEWER_DIAGNOSTICS__!.snapshot().renderedPhotos.ready)).toBeGreaterThan(0)
  expect(errors).toEqual([])
})
